    var out = input + Array(repeating: 0, count: 256)
    var buf = input + [input.reduce(0, ^)]
    for round in 0..<16 {
      for i in 0..<17 { buf[i] = ((buf[i] << 3) | (buf[i] >> 5)) & 255 }
      for j in 0..<16 {
        out[16 + round * 16 + j] = (KS_TABLE[15 + round * 16 - j] + buf[(round + 1 + j) % 17]) & 255
      }
    }
    return out
  }
