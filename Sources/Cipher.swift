  static func mix(_ s: [Int], _ key: [Int], _ phase: Int) -> [Int] {
    (0..<16).map { i in
      let xor = (((1 << i) & 0x9999) != 0) == (phase == 3)
      return xor ? s[i] ^ key[i] : (s[i] + key[i]) & 255
    }
  }
  static func sub(_ s: [Int]) -> [Int] {
    (0..<16).map { i in [0, 3, 4, 7, 8, 11, 12, 15].contains(i) ? SBOX[s[i]] : ISBOX[s[i]] }
  }
  static func block(_ input: [Int], _ key: [Int], _ mode: Int) -> [Int] {
    var s = mix(sub(mix(input, Array(key[0..<16]), 3)), Array(key[16..<32]), 5)
    for round in 1...8 {
      s = fibonacci(s)
      if round == 8 {
        s = mix(s, Array(key[256..<272]), 3)
        break
      }
      if mode != 0 && round == 2 { s = mix(s, input, 3) }
      let off = round * 32
      s = mix(sub(mix(s, Array(key[off..<off + 16]), 3)), Array(key[off + 16..<off + 32]), 5)
    }
    return s
  }
  static func encrypt(_ input: [UInt8]) -> [UInt8] {
    precondition(input.count == 16)
    let data = input.map(Int.init)
    var out = block(data, schedule(STATIC_KEY), 0)
    for i in 0..<16 { out[i] = (MAGIC[i % 6] + (out[i] ^ data[i])) & 255 }
    let constants = [
      0x17, 0xE5, 0x21, 0xC1, 0x4D, 0xA7, 0x6B, 0x83, 0xE9, 0x1B, 0xDF, 0x3F, 0xB3, 0x59, 0x95,
      0x7D,
    ]
    let subtract = [0, 2, 4, 6, 9, 11, 13, 15]
    let obf = (0..<16).map {
      subtract.contains($0)
        ? (STATIC_KEY[$0] - constants[$0]) & 255 : STATIC_KEY[$0] ^ constants[$0]
    }
    return block(out, schedule(obf), 1).map { UInt8($0) }
  }
